/// Identifier of a node within a revision tree.
pub type NodeID = u32;

pub const ROOT_NODE: NodeID = 0;
pub const INVALID_NODE: NodeID = 0xFFFFFFFF;
pub const INVALID_BLOCK: u32 = 0xFFFFFFFF;

pub fn node_to_file_metadata(node: NodeID) -> u32 {
    node
}

pub trait NodeIDExt {
    fn is_valid_node_id(&self) -> bool;
    fn is_valid_or_root_node_id(&self) -> bool;
}

impl NodeIDExt for NodeID {
    fn is_valid_node_id(&self) -> bool {
        *self != ROOT_NODE && *self != INVALID_NODE
    }

    fn is_valid_or_root_node_id(&self) -> bool {
        *self != INVALID_NODE
    }
}

/// Number of bits to shift a full index to get block index
const BLOCK_NODE_SHIFT: u32 = 9;
/// Number of nodes in a block
pub const BLOCK_NODE_COUNT: usize = 512;
/// Bitmask for node index in a full index
const NODE_INDEX_MASK: u32 = (1u32 << BLOCK_NODE_SHIFT) - 1;
/// Maximum size of the per-block node name buffer. Each [`NodeBlock`] holds up
/// to [`BLOCK_NODE_COUNT`] nodes, and the total concatenated name data is
/// capped at this size (4 MiB = ~8 KiB per node, far larger than any
/// legitimate path component). Rejecting further appends prevents a single
/// block from consuming unbounded memory, and bounds the allocation on
/// deserialize.
pub const NODE_NAME_MAX_SIZE: usize = 4 * 1024 * 1024;
/// Maximum byte length of a single node name, matching the bound branch and
/// repository names use. Enforced when a name is stored, not when one is read,
/// so a tree written before the bound existed stays readable.
pub const MAX_NODE_NAME_LEN: usize = 1000;

bitflags! {
    #[repr(transparent)]
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct NodeBlockFlags: u32 {
        /// Node block is dirty
        const Dirty = 0b1;
        /// Node block got first block discarded and unused
        const FirstUnusedNode = 0b10;
        /// Name table should be repacked
        const RepackNametable = 0b100;
        /// Never written. See [`NODE_BLOCK_RUNTIME_FLAGS`].
        const DeferRepackNametable = 0b1000;
        /// Name table was generated by data format upgrade
        const UpgradeGeneratedNametable = 0b10000000000000000;
    }
}
bitflagsops!(NodeBlockFlags, u32);

/// The [`NodeBlockFlags`] bits that are never stored.
///
/// The state they described belongs to this process, not to the block, so it is
/// held as plain fields on [`NodeBlockRuntimeData`] instead, or, for a repack a
/// freed slot deferred, not held at all: a repack keeps every name but a free
/// slot's (C3). Nothing writes these bits any more; they stay declared so their
/// values are not given a stored meaning by a later change, and so a block from
/// a store written before the split can be cleared of them on the way in.
///
/// Keeping them out of [`NodeBlockData`] is what lets `State::serialize` write a
/// block straight from its lock: with nothing to clear first, it no longer has
/// to copy the block out to produce the image.
pub const NODE_BLOCK_RUNTIME_FLAGS: u32 = NodeBlockFlags::Dirty.bits()
    | NodeBlockFlags::FirstUnusedNode.bits()
    | NodeBlockFlags::DeferRepackNametable.bits()
    | NodeBlockFlags::UpgradeGeneratedNametable.bits();

