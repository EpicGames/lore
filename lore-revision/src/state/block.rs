/// Read accessor for a file metadata block that can be held across an await.
/// See [`NodeBlockOwnedReader`].
pub struct NodeFileMetadataBlockOwnedReader {
    lock: parking_lot::ArcRwLockReadGuard<parking_lot::RawRwLock, NodeFileMetadataBlockRuntimeData>,
}

// SAFETY: see [`NodeBlockOwnedReader`].
unsafe impl Send for NodeFileMetadataBlockOwnedReader {}

impl NodeFileMetadataBlockOwnedReader {
    /// The block exactly as it is to be stored.
    pub fn node_block(&self) -> &NodeFileMetadataBlockData {
        &self.lock.data
    }
}

impl Default for NodeFileMetadataBlock {
    fn default() -> Self {
        Self::new(NodeFileMetadataBlockData::new_from_heap_zeroed())
    }
}

impl NodeFileMetadataBlock {
    pub fn new(mut data: HeapBox<NodeFileMetadataBlockData>) -> Self {
        // As in `NodeBlock::clear_runtime_flags`: drop what an older store may
        // carry, and start the runtime state clear.
        data.flags &= !NodeFileMetadataBlockFlags::Dirty;
        NodeFileMetadataBlock {
            data: Arc::new(RwLock::new(NodeFileMetadataBlockRuntimeData {
                data,
                dirty: false,
                edits: 0,
                saved_edits: AtomicU64::new(0),
            })),
            registered: AtomicBool::new(false),
            #[cfg(feature = "state-hooks")]
            hook_name: std::sync::OnceLock::new(),
        }
    }

    /// Under `state-hooks`, names this block's lock by the installing State's `ordinal` and its
    /// `index`.
    #[cfg(feature = "state-hooks")]
    pub(crate) fn set_hook_name(&self, ordinal: usize, index: usize) {
        let _ = self.hook_name.set((ordinal, index));
    }

    /// Under `state-hooks`, records that the running step read or wrote this block's lock, once
    /// taken, where a State installed it.
    #[cfg(feature = "state-hooks")]
    fn hook_touch(&self, write: bool) {
        if let Some(&(ordinal, index)) = self.hook_name.get() {
            crate::state::node::hooks::touched(
                crate::state::node::hooks::Resource::MetadataBlock(ordinal, index),
                write,
            );
        }
    }

    /// [`NodeBlock::claim_registration`] for a file metadata block.
    #[inline]
    pub(crate) fn claim_registration(&self) -> bool {
        !self.registered.swap(true, Ordering::AcqRel)
    }

    /// [`NodeBlock::keep_registration`] for a file metadata block.
    #[inline]
    pub(crate) fn keep_registration(&self) -> bool {
        let reader = self.read();
        let dirty = reader.is_dirty();
        if !dirty {
            self.registered.store(false, Ordering::Release);
        }
        dirty
    }

    /// Take a read lock that can be held across an await. See
    /// [`NodeBlockOwnedReader`].
    pub fn read_owned(&self) -> NodeFileMetadataBlockOwnedReader {
        let lock = self.data.read_arc();
        #[cfg(feature = "state-hooks")]
        self.hook_touch(false);
        NodeFileMetadataBlockOwnedReader { lock }
    }

    /// A save's image of this block, read under one lock with the edit sequence it holds, which
    /// is recorded for [`Self::release_saved`]. A file metadata block has no name table, so
    /// the image is the one read.
    pub fn read_saving(&self) -> NodeFileMetadataBlockOwnedReader {
        let reader = self.read_owned();
        reader
            .lock
            .saved_edits
            .store(reader.lock.edits, Ordering::Relaxed);
        reader
    }

    /// Clears the block's dirty flag unless an edit marked it since its image, as a node block's
    /// `release_saved` does.
    pub fn release_saved(&self) {
        let mut lock = self.data.write();
        #[cfg(feature = "state-hooks")]
        self.hook_touch(true);
        if lock.edits == *lock.saved_edits.get_mut() {
            lock.dirty = false;
        }
    }

    /// Get the block index from a full node ID
    pub fn index(node: NodeID) -> usize {
        (node >> BLOCK_NODE_SHIFT) as usize
    }

    pub fn read(&self) -> NodeFileMetadataBlockReader<'_> {
        let lock = self.data.read();
        #[cfg(feature = "state-hooks")]
        self.hook_touch(false);
        NodeFileMetadataBlockReader { lock }
    }

    pub fn write(&self) -> NodeFileMetadataBlockWriter<'_> {
        let lock = self.data.write();
        #[cfg(feature = "state-hooks")]
        self.hook_touch(true);
        NodeFileMetadataBlockWriter { lock }
    }

    pub fn node(&self, node_index: usize) -> NodeFileMetadata {
        *self.read().node(node_index)
    }
}

impl NodeFileMetadataBlockReader<'_> {
    /// Get the node for the given node index
    pub fn node(&self, node_index: usize) -> &NodeFileMetadata {
        debug_assert!(node_index < BLOCK_NODE_COUNT);
        &self.lock.data.node[node_index]
    }

    /// Access the full node block
    pub fn node_block(&self) -> &NodeFileMetadataBlockData {
        &self.lock.data
    }

    /// Whether the block holds edits that are not in the store yet.
    pub fn is_dirty(&self) -> bool {
        self.lock.dirty
    }
}

impl NodeFileMetadataBlockWriter<'_> {
    /// Get the node for the given node index
    pub fn node(&mut self, node_index: usize) -> &mut NodeFileMetadata {
        debug_assert!(node_index < BLOCK_NODE_COUNT);
        &mut self.lock.data.node[node_index]
    }

    /// Marks the block dirty, bumping its edit sequence, as [`NodeBlockWriter::mark_dirty`].
    pub fn mark_dirty(&mut self) -> bool {
        let was_dirty = self.lock.dirty;
        self.lock.dirty = true;
        self.lock.edits = self.lock.edits.wrapping_add(1);
        !was_dirty
    }
}

/// The accessors, wrappers and constructors a `test-util` build adds to this module's types, for
/// tests.
#[cfg(feature = "test-util")]
mod test_util {
    use super::*;

    impl ChainLog {
        /// Empties the log at sequence `position`, for tests that run it across the wrap.
        pub fn restart_at_for_tests(&mut self, position: u32) {
            self.seq = position;
            self.floor = position;
        }
    }

    impl NodeBlock {
        /// Whether the block is registered for the State's next save. For tests.
        pub fn is_registered(&self) -> bool {
            self.registered.load(Ordering::Acquire)
        }

        /// A read lock that can be held across an await. See [`NodeBlockOwnedReader`].
        pub fn read_owned(&self) -> NodeBlockOwnedReader {
            let lock = self.read_arc_guard();
            NodeBlockOwnedReader {
                #[cfg(feature = "state-hooks")]
                _hold: self
                    .hooks
                    .owned_hold(crate::state::node::hooks::Mode::Read, false),
                lock,
            }
        }

        /// The `saving` hold, for tests that hold a block as a save does.
        pub fn saving_for_tests(&self) -> NodeBlockSaving {
            self.saving()
        }

        /// The block's write access, for tests that write node blocks directly.
        pub fn write_for_tests(&self) -> NodeBlockWriter<'_> {
            self.write()
        }

        /// The name of the node at `node_index`, copied out, as the read path checks it.
        pub fn node_name_clone(&self, node_index: usize) -> Result<String, NodeNameError> {
            #[cfg(feature = "state-hooks")]
            let _order = self.lock_order();
            let guard = self.read_data();
            Self::name_in(&guard, &guard.data.node[node_index]).map(str::to_string)
        }

        /// The name table's load, for tests that load it directly.
        pub async fn deserialize_nametable_for_tests(
            &self,
            repository: Arc<RepositoryContext>,
        ) -> Result<(), StateError> {
            self.deserialize_nametable(repository).await
        }

        /// [`NodeBlockWriter::node_name_repack`] under this block's write lock.
        pub fn node_name_repack(&self) {
            let mut lock = self.write();
            lock.node_name_repack();
        }
    }

    impl NodeBlockReader<'_> {
        /// The block's name table, copied out.
        pub fn clone_name_table(&self) -> bytes::Bytes {
            bytes::Bytes::copy_from_slice(&self.lock.name)
        }

        /// How many of the block's directories have a chain log.
        pub fn chain_log_count(&self) -> usize {
            self.lock.chain_logs.len()
        }
    }

    impl NodeBlockWriter<'_> {
        /// Rewrites the name table, where a name appended to it flagged a repack, with the names of
        /// every slot but the free ones, those on the block's free list. A Discarded slot off the
        /// list keeps its name: a detached record keeps it for its life (C3), and a slot an attach
        /// holds is Discarded from its grab to its publish (H8), its name already stored.
        pub fn node_name_repack(&mut self) {
            if self.lock.wants_repack() {
                self.lock.repack_names();
            }
        }
    }

    impl NodeFileMetadataBlock {
        /// [`NodeBlock::is_registered`] for a file metadata block. For tests.
        pub fn is_registered(&self) -> bool {
            self.registered.load(Ordering::Acquire)
        }
    }
}
