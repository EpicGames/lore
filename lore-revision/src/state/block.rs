/// Patches a chain log holds from its directory's first listing.
pub const CHAIN_LOG_INITIAL: usize = 16;
/// How many times larger a full log grows at a watch.
pub const CHAIN_LOG_GROWTH: usize = 4;
/// Patches a chain log holds once a listing build grew it the first time.
#[cfg(feature = "test-util")]
pub const CHAIN_LOG_GROWN: usize = CHAIN_LOG_INITIAL * CHAIN_LOG_GROWTH;
/// Patches a chain log holds at most; a full log of this size stays as it is.
pub const CHAIN_LOG_MAX: usize = 1024;

/// What a [`ChainPatch`] records.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum PatchKind {
    Attached,
    Detached,
}

/// One change to a directory's child chain: `node`, under `name_hash`, attached or detached.
/// `block` is the node's block, weak so a patch pins nothing and forms no cycle: a VFS listing
/// reads an attached node's record from it with no State lock.
#[derive(Clone, Debug)]
pub struct ChainPatch {
    pub name_hash: u64,
    pub block: std::sync::Weak<NodeBlock>,
    pub node: NodeID,
    pub kind: PatchKind,
}

/// A ring of the latest changes to one directory's child chain, written under the directory
/// block's write lock by the State primitives that change the chain, read under its read lock.
#[derive(Debug)]
pub struct ChainLog {
    /// Patches ever appended; the ring holds sequences `[floor, seq)`.
    seq: u32,
    /// The oldest sequence still held; `seq - floor` never exceeds the capacity.
    floor: u32,
    /// Detached patches ever appended.
    detaches: u32,
    /// Renames in place that kept the name hash.
    respells: u32,
    /// Patch `s` at `s % len`; `len` is a power of two, so the slot survives `seq` wrapping.
    patches: Box<[Option<ChainPatch>]>,
}

struct ChainLogSlot {
    index: u16,
    log: Box<ChainLog>,
}

const _: () = assert!(std::mem::size_of::<Option<ChainPatch>>() == 24);
const _: () = assert!(std::mem::size_of::<ChainLog>() == 32);
const _: () = assert!(std::mem::size_of::<ChainLogSlot>() == 16);

/// A directory's log position and its counts, read in one bracket with its record by
/// [`NodeBlock::watch_chain`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct LogMark {
    pub seq: u32,
    pub detaches: u32,
    pub respells: u32,
}

impl ChainLog {
    fn new(capacity: usize) -> Self {
        Self {
            seq: 0,
            floor: 0,
            detaches: 0,
            respells: 0,
            patches: empty_ring(capacity),
        }
    }

    /// The patches the ring holds at most.
    pub fn capacity(&self) -> usize {
        self.patches.len()
    }

    /// Patches ever appended, wrapping: the sequence the next append takes.
    pub fn seq(&self) -> u32 {
        self.seq
    }

    /// The oldest sequence the ring still holds.
    pub fn floor(&self) -> u32 {
        self.floor
    }

    /// Detached patches ever appended, wrapping.
    pub fn detaches(&self) -> u32 {
        self.detaches
    }

    /// Renames in place that kept the name hash, wrapping.
    pub fn respells(&self) -> u32 {
        self.respells
    }

    /// The ring is full, so its next append drops a patch, and below [`CHAIN_LOG_MAX`], so the
    /// next watch grows it.
    fn overflowed(&self) -> bool {
        let len = self.patches.len();
        self.seq.wrapping_sub(self.floor) as usize == len && len < CHAIN_LOG_MAX
    }

    /// Writes `patch` as sequence `seq`, over the oldest patch once the ring is full, which
    /// moves the floor past it. Under the directory block's write lock.
    #[lore_macro::test_pub]
    pub(crate) fn append(&mut self, patch: ChainPatch) {
        if patch.kind == PatchKind::Detached {
            self.detaches = self.detaches.wrapping_add(1);
        }
        let len = self.patches.len();
        self.patches[self.seq as usize % len] = Some(patch);
        self.seq = self.seq.wrapping_add(1);
        if self.seq.wrapping_sub(self.floor) as usize > len {
            self.floor = self.floor.wrapping_add(1);
        }
    }

    /// Takes sequence `seq` for a change it holds no patch for and moves the floor to the head,
    /// so every earlier position is outside the window and its readers answer stale.
    #[lore_macro::test_pub]
    pub(crate) fn skip(&mut self, kind: PatchKind) {
        if kind == PatchKind::Detached {
            self.detaches = self.detaches.wrapping_add(1);
        }
        self.seq = self.seq.wrapping_add(1);
        self.floor = self.seq;
    }

    /// Counts a rename in place that kept the name hash, which no patch tells from no change.
    #[lore_macro::test_pub]
    pub(crate) fn respell(&mut self) {
        self.respells = self.respells.wrapping_add(1);
    }

    /// Drops every patch the log holds, its slot freed: a reader at an earlier position finds
    /// the log no longer covers it, so no patch of the freed directory speaks for the slot taken
    /// again.
    fn forget(&mut self) {
        self.floor = self.seq;
    }

    /// Whether the log holds no patch.
    pub fn holds_no_patch(&self) -> bool {
        self.seq == self.floor
    }

    /// Whether a reader at `position` finds every patch since in the log: `floor <= position <=
    /// seq`. Any other position is stale, never a miss.
    pub fn covers(&self, position: u32) -> bool {
        self.seq.wrapping_sub(position) <= self.seq.wrapping_sub(self.floor)
    }

    /// Patch `sequence`, if it lies in `[floor, seq)`.
    pub fn patch(&self, sequence: u32) -> Option<&ChainPatch> {
        let back = self.seq.wrapping_sub(sequence);
        if back == 0 || back > self.seq.wrapping_sub(self.floor) {
            return None;
        }
        self.patches[sequence as usize % self.patches.len()].as_ref()
    }

    /// The newest patch for `name_hash` among those from `since` on, scanned newest first.
    pub fn newest(&self, name_hash: u64, since: u32) -> Newest<'_> {
        if !self.covers(since) {
            return Newest::Uncovered;
        }
        let mut sequence = self.seq;
        while sequence != since {
            sequence = sequence.wrapping_sub(1);
            let Some(patch) = self.patch(sequence) else {
                return Newest::Uncovered;
            };
            if patch.name_hash == name_hash {
                return Newest::Patch(patch);
            }
        }
        Newest::Nothing
    }
}

/// What [`ChainLog::newest`] found for a name hash since a log position.
#[derive(Debug)]
pub enum Newest<'a> {
    /// The log no longer holds every patch since the position.
    Uncovered,
    /// No patch since the position names the hash.
    Nothing,
    Patch(&'a ChainPatch),
}

