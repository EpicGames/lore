/// A process-wide count of block reads that found a writer holding or taking the block, while
/// enabled, so a test can show whether readers wait on writers. Built only for tests: a build
/// without `test-util`, or a bench build (`bench`), counts nothing and pays nothing.
#[cfg(feature = "test-util")]
pub mod read_contention {
    use std::sync::atomic::AtomicBool;
    use std::sync::atomic::AtomicU64;
    use std::sync::atomic::Ordering;

    static COUNTING: AtomicBool = AtomicBool::new(false);
    static CONTENDED: AtomicU64 = AtomicU64::new(0);

    /// Enables or disables counting process-wide. Disabled by default.
    pub fn set_contended_read_counting(enabled: bool) {
        COUNTING.store(enabled, Ordering::Relaxed);
    }

    /// Contended block reads counted on every thread.
    pub fn contended_reads() -> u64 {
        CONTENDED.load(Ordering::Relaxed)
    }

    #[cfg(not(feature = "bench"))]
    #[inline]
    pub(crate) fn enabled() -> bool {
        COUNTING.load(Ordering::Relaxed)
    }

    #[cfg(not(feature = "bench"))]
    pub(crate) fn record() {
        CONTENDED.fetch_add(1, Ordering::Relaxed);
    }
}

/// Under `state-hooks`, what names a node block to the scheduler, and the lock probe: who holds
/// the block's data lock, in a few slots, so a task finding the lock held can name the holders
/// ([`crate::state::node::hooks::Contention`]).
#[cfg(feature = "state-hooks")]
mod probe {
    use std::sync::Arc;
    use std::sync::OnceLock;
    use std::sync::atomic::AtomicU64;
    use std::sync::atomic::AtomicUsize;
    use std::sync::atomic::Ordering;

    use crate::state::node::hooks;
    use crate::state::node::hooks::HOLDER_SLOTS;
    use crate::state::node::hooks::Holder;
    use crate::state::node::hooks::Mode;
    use crate::state::node::hooks::StateHooks;

    /// A slot's value: the mode in the low two bits, and the holder's task plus one above them,
    /// 0 for a holder outside a task. 0 is a free slot.
    fn encode(task: Option<usize>, mode: Mode) -> u64 {
        let mode = match mode {
            Mode::Read => 1,
            Mode::Write => 2,
            Mode::Upgradable => 3,
        };
        (task.map_or(0, |task| task as u64 + 1) << 2) | mode
    }

    fn decode(value: u64) -> Option<Holder> {
        let mode = match value & 3 {
            0 => return None,
            1 => Mode::Read,
            2 => Mode::Write,
            _ => Mode::Upgradable,
        };
        Some(Holder {
            task: (value >> 2).checked_sub(1).map(|task| task as usize),
            mode,
        })
    }

    /// The holders of a block's lock: the writer's or upgradable reader's slot, which one holder
    /// at a time can take, and a few readers' slots.
    #[derive(Default)]
    pub(super) struct Slots {
        writer: AtomicU64,
        readers: [AtomicU64; HOLDER_SLOTS - 1],
    }

    /// No slot: every reader's slot was taken.
    const NO_SLOT: usize = usize::MAX;

    impl Slots {
        /// Takes a slot for the running task holding the lock in `mode`: 0, the writer's, or a
        /// free reader's; [`NO_SLOT`] where every reader's slot is taken.
        fn open(&self, mode: Mode) -> usize {
            let value = encode(hooks::task(), mode);
            if mode != Mode::Read {
                self.writer.store(value, Ordering::Release);
                return 0;
            }
            self.readers
                .iter()
                .position(|slot| {
                    slot.compare_exchange(0, value, Ordering::AcqRel, Ordering::Relaxed)
                        .is_ok()
                })
                .map_or(NO_SLOT, |at| at + 1)
        }

        fn close(&self, slot: usize) {
            match slot {
                NO_SLOT => {}
                0 => self.writer.store(0, Ordering::Release),
                at => self.readers[at - 1].store(0, Ordering::Release),
            }
        }

        /// The holders named now.
        pub(super) fn holders(&self) -> [Option<Holder>; HOLDER_SLOTS] {
            let mut holders = [None; HOLDER_SLOTS];
            holders[0] = decode(self.writer.load(Ordering::Acquire));
            for (holder, slot) in holders[1..].iter_mut().zip(&self.readers) {
                *holder = decode(slot.load(Ordering::Acquire));
            }
            holders
        }
    }

    /// A borrowed guard's hold on its block's slots, declared before the guard so it closes
    /// before the lock is released.
    pub(super) struct Hold<'a> {
        slots: &'a Slots,
        slot: usize,
    }

    impl Drop for Hold<'_> {
        fn drop(&mut self) {
            self.slots.close(self.slot);
        }
    }

    /// An owned guard's hold, which may close on another thread. Unless it is a save's, it is
    /// counted in the open owned holds of the task that took it, which may not park holding one
    /// (C13).
    pub(super) struct OwnedHold {
        slots: Arc<Slots>,
        slot: usize,
        task: Option<Arc<AtomicUsize>>,
    }

    impl OwnedHold {
        /// Closes the hold's slot, where the lock is to change hands: a save's image, before the
        /// downgrade lets another upgradable reader in to take the writer's slot.
        pub(super) fn release(&mut self) {
            self.slots.close(self.slot);
            self.slot = NO_SLOT;
        }

        /// The hold, released, now in `mode`: a save's image, its lock downgraded to a read.
        pub(super) fn reopen(mut self, mode: Mode) -> Self {
            assert!(self.slot == NO_SLOT, "a hold reopens once released");
            self.slot = self.slots.open(mode);
            self
        }
    }

    impl Drop for OwnedHold {
        fn drop(&mut self) {
            self.slots.close(self.slot);
            if let Some(task) = &self.task {
                task.fetch_sub(1, Ordering::Relaxed);
            }
        }
    }

    /// A block's hooks: the index and the State it was installed at, and its holders.
    pub(super) struct BlockHooks {
        /// The index the State installed the block at, which names it in footprints the same
        /// way in every run; `usize::MAX` until installed, when no other task can reach it.
        pub(super) index: AtomicUsize,
        /// The installing State's hooks: its ordinal, its bound, its count of live blocks.
        pub(super) state: OnceLock<Arc<StateHooks>>,
        /// The block's instance in its State, which tells its records from those of an evicted
        /// block at its index.
        pub(super) instance: std::sync::atomic::AtomicU64,
        slots: Arc<Slots>,
    }

    impl BlockHooks {
        pub(super) fn new() -> Self {
            Self {
                index: AtomicUsize::new(usize::MAX),
                state: OnceLock::new(),
                instance: std::sync::atomic::AtomicU64::new(0),
                slots: Arc::default(),
            }
        }

        /// Holds a slot for the running task holding the lock in `mode`.
        pub(super) fn hold(&self, mode: Mode) -> Hold<'_> {
            Hold {
                slots: &self.slots,
                slot: self.slots.open(mode),
            }
        }

        /// [`Self::hold`] for an owned guard, counted in its task's open owned holds unless a
        /// save takes it.
        pub(super) fn owned_hold(&self, mode: Mode, save: bool) -> OwnedHold {
            let task = if save { None } else { hooks::task_holds() };
            if let Some(task) = &task {
                task.fetch_add(1, Ordering::Relaxed);
            }
            OwnedHold {
                slots: self.slots.clone(),
                slot: self.slots.open(mode),
                task,
            }
        }

        /// The installing State's ordinal and the block's index, where installed.
        pub(super) fn name(&self) -> Option<(usize, usize)> {
            let index = self.index.load(Ordering::Acquire);
            if index == usize::MAX {
                return None;
            }
            self.state.get().map(|state| (state.ordinal(), index))
        }

        /// Tells the scheduler a try found the lock held, where the block is installed, and
        /// answers what it told, for [`Self::taken`] once the lock is taken.
        pub(super) fn contended(&self, mode: Mode) -> Option<hooks::Contention> {
            let (ordinal, index) = self.name()?;
            let contention = hooks::Contention {
                block: hooks::Resource::Block(ordinal, index),
                waiter: hooks::task(),
                mode,
                holders: self.slots.holders(),
            };
            hooks::contended(&contention);
            Some(contention)
        }

        /// The log's arm of a lock found held, made once the lock is taken: the record is not made
        /// in the window where the task blocks.
        pub(super) fn taken(&self, contention: Option<hooks::Contention>) {
            if let (Some(contention), Some(state)) = (contention, self.state.get()) {
                hooks::log::arm(
                    state,
                    hooks::log::Arm::Contended {
                        block: contention.block,
                        waiter: contention.waiter,
                        mode: contention.mode,
                        holders: contention.holders,
                    },
                );
            }
        }
    }

    impl Drop for BlockHooks {
        fn drop(&mut self) {
            if let Some(state) = self.state.get() {
                state.block_dropped();
            }
        }
    }
}

