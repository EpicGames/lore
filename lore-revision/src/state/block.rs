/// A node in the revision tree, 96 bytes (32 bit index, max 4G nodes)
#[repr(C)]
#[derive(Debug, Default, Copy, Clone, IntoBytes, FromBytes, Immutable)]
pub struct Node {
    /// Flags
    pub flags: u16,
    /// File - Executable flag in first bit
    pub mode: u16,
    /// Unused
    pub _unused: u32,
    /// Directory - first child index
    /// Submodule - Target tree node
    pub child: u32,
    /// Parent index
    pub parent: u32,
    /// Next sibling index
    pub sibling: u32,
    /// Name string offset
    pub name_offset: u32,
    /// Name string length
    pub name_length: u32,
    /// Extension flags, [`NodeExtFlags`]
    pub ext_flags: u32,
    /// Name hash (case insensitive)
    pub name_hash: u64,
    /// File size
    pub size: u64,
    /// Node content address
    /// - For files this is the content payload (content hash and file ID).
    /// - For directories the hash of every child's name and content, in ascending order of name
    ///   hash; see [`rehash_directory`](crate::commit::rehash_directory).
    /// - For a submodule this is the target revision hash and repository ID.
    pub address: Address,
}

impl Node {
    /// Check if node is staged for inclusion in a commit
    pub fn is_staged(&self) -> bool {
        (self.flags & NodeFlags::Staged) == NodeFlags::Staged.bits()
    }

    /// The staged change this node carries, as the API surface names it.
    ///
    /// Reports [`LoreNodeStagedAction::None`] for a node with no staging bits,
    /// which is every node of a freshly loaded revision — commit clears the
    /// change flags on what it writes. Delete is tested before add so a node
    /// staged for addition and then staged for deletion reports the deletion.
    pub fn staged_action(&self) -> LoreNodeStagedAction {
        if !self.is_staged() {
            return LoreNodeStagedAction::None;
        }
        if self.is_staged_delete() {
            LoreNodeStagedAction::Delete
        } else if self.is_staged_add() {
            LoreNodeStagedAction::Add
        } else if self.is_staged_move() {
            LoreNodeStagedAction::Move
        } else if self.is_staged_copy() {
            LoreNodeStagedAction::Copy
        } else if self.is_staged_modify() {
            LoreNodeStagedAction::Modify
        } else {
            LoreNodeStagedAction::None
        }
    }

    /// Check if node is staged for deletion
    pub fn is_staged_delete(&self) -> bool {
        (self.flags & NodeFlags::StagedDelete) == NodeFlags::StagedDelete.bits()
    }

    /// Check if node is staged for add
    pub fn is_staged_add(&self) -> bool {
        (self.flags & NodeFlags::StagedAdd) == NodeFlags::StagedAdd.bits()
    }

    /// Check if node is staged for modify
    pub fn is_staged_modify(&self) -> bool {
        (self.flags & NodeFlags::StagedModify) == NodeFlags::StagedModify.bits()
    }

    /// Check if node is staged for move
    pub fn is_staged_move(&self) -> bool {
        (self.flags & NodeFlags::StagedMove) == NodeFlags::StagedMove.bits()
    }

    /// Check if node is staged for copy
    pub fn is_staged_copy(&self) -> bool {
        (self.flags & NodeFlags::StagedCopy) == NodeFlags::StagedCopy.bits()
    }

    /// Check if node is part of a merge
    pub fn is_staged_merge(&self) -> bool {
        (self.flags & NodeFlags::StagedMerge) == NodeFlags::StagedMerge.bits()
    }

    /// Check if node is part of a conflict - either resolved or unresolved
    pub fn is_staged_merge_conflict(&self) -> bool {
        (self.flags & NodeFlags::StagedMergeConflict) == NodeFlags::StagedMergeConflict.bits()
    }

    /// Check if node is part of a conflict - resolved
    pub fn is_staged_merge_resolved(&self) -> bool {
        (self.flags & NodeFlags::StagedMergeResolved) == NodeFlags::StagedMergeResolved.bits()
    }

    /// Check if node is part of a conflict - unresolved
    pub fn is_staged_merge_unresolved(&self) -> bool {
        self.is_staged_merge_conflict() && !self.is_staged_merge_resolved()
    }

    /// Check if node is part of a conflict and the mine version got staged
    pub fn is_staged_merge_mine(&self) -> bool {
        (self.flags & NodeFlags::StagedMergeMine) == NodeFlags::StagedMergeMine.bits()
    }

    /// Check if node is part of a conflict and the theirs version got staged
    pub fn is_staged_merge_theirs(&self) -> bool {
        (self.flags & NodeFlags::StagedMergeTheirs) == NodeFlags::StagedMergeTheirs.bits()
    }

    /// Check if the node is a file
    pub fn is_file(&self) -> bool {
        (self.flags & NodeFlags::File) == NodeFlags::File.bits()
    }

    /// Check if the node is a link
    pub fn is_link(&self) -> bool {
        (self.flags & NodeFlags::Link) == NodeFlags::Link.bits()
    }

    /// Check if the node is a directory
    pub fn is_directory(&self) -> bool {
        !self.is_file() && !self.is_link()
    }

    /// Whether the filter is asked about a path a command names as a directory, where the tree
    /// holds `node` there: unless it is a file, a link counting as the directory it mounts, and
    /// where the tree holds nothing.
    pub fn asked_as_directory(node: Option<&Node>) -> bool {
        node.is_none_or(|node| !node.is_file())
    }

    pub fn node_type(&self) -> LoreNodeType {
        NodeFlags::from_bits_retain(self.flags).node_type()
    }

    /// Check if node is marked as discarded
    pub fn is_discarded(&self) -> bool {
        (self.flags & NodeFlags::Discarded) == NodeFlags::Discarded.bits()
    }

    /// Check if node is dirty (filesystem change detected)
    pub fn is_dirty(&self) -> bool {
        (self.flags & NodeFlags::Dirty) == NodeFlags::Dirty.bits()
    }

    /// Check if node is dirty with modify action
    pub fn is_dirty_modify(&self) -> bool {
        (self.flags & NodeFlags::DirtyModify) == NodeFlags::DirtyModify.bits()
    }

    /// Check if node is dirty with add action
    pub fn is_dirty_add(&self) -> bool {
        (self.flags & NodeFlags::DirtyAdd) == NodeFlags::DirtyAdd.bits()
    }

    /// Check if node is dirty with delete action
    pub fn is_dirty_delete(&self) -> bool {
        (self.flags & NodeFlags::DirtyDelete) == NodeFlags::DirtyDelete.bits()
    }

    /// Check if node is dirty with move action
    pub fn is_dirty_move(&self) -> bool {
        (self.flags & NodeFlags::DirtyMove) == NodeFlags::DirtyMove.bits()
    }

    /// Check if node is dirty with copy action
    pub fn is_dirty_copy(&self) -> bool {
        (self.flags & NodeFlags::DirtyCopy) == NodeFlags::DirtyCopy.bits()
    }

    /// Check if node is dirty or staged (has any lifecycle change)
    pub fn is_dirty_or_staged(&self) -> bool {
        self.is_dirty() || self.is_staged()
    }

    /// Check if node carries the add action, staged or dirty: the two halves share their action
    /// bits, which hold one change at a time
    pub fn is_added(&self) -> bool {
        self.is_staged_add() || self.is_dirty_add()
    }

    /// Check if node carries the delete action, staged or dirty
    pub fn is_deleted(&self) -> bool {
        self.is_staged_delete() || self.is_dirty_delete()
    }

    /// Check if node has any change flags (`Dirty`, `Staged`, or `ActionBits`)
    pub fn has_any_change_flags(&self) -> bool {
        (self.flags & (NodeFlags::Dirty.bits() | NodeFlags::StagedBits.bits())) != 0
    }

    /// Extract just the action bits (bits 5-9) from the node flags
    pub fn action_bits(&self) -> u16 {
        self.flags & NodeFlags::ActionBits.bits()
    }

    /// The node's extension flags.
    pub fn ext_flags(&self) -> NodeExtFlags {
        NodeExtFlags::from_bits_retain(self.ext_flags)
    }

    /// Clear staged flags. Preserves `Dirty` and action bits if `Dirty` is set.
    /// Clears `Staged` (bit 4) + `MergeBits` (10-14). Clears `ActionBits` only if `Dirty` is not set.
    pub fn clear_staged_flags(&mut self) {
        let has_dirty = self.is_dirty();
        self.flags &= !(NodeFlags::Staged.bits() | NodeFlags::MergeBits.bits());
        if !has_dirty {
            self.flags &= !NodeFlags::ActionBits.bits();
        }
    }

    /// Clear dirty flags. Preserves `Staged` and action bits if `Staged` is set.
    /// Clears `Dirty` (bit 3) and the extension flags. Clears `ActionBits` only if `Staged` is
    /// not set.
    pub fn clear_dirty_flags(&mut self) {
        let has_staged = self.is_staged();
        self.flags &= !NodeFlags::Dirty.bits();
        self.ext_flags = 0;
        if !has_staged {
            self.flags &= !NodeFlags::ActionBits.bits();
        }
    }

    /// Clear all change flags (`Dirty` + `Staged` + `ActionBits` + `MergeBits`) and the
    /// extension flags. Preserves type flags.
    pub fn clear_all_change_flags(&mut self) {
        self.flags &= !(NodeFlags::Dirty.bits() | NodeFlags::StagedBits.bits());
        self.ext_flags = 0;
    }

    const fn index_clamp(index: u32) -> u32 {
        if index < BLOCK_NODE_COUNT as u32 {
            index
        } else {
            0
        }
    }

    /// Get the node index from a full node ID
    pub fn index(node: NodeID) -> usize {
        Self::index_clamp(node & NODE_INDEX_MASK) as usize
    }

    /// Get the first child node (only for directory nodes)
    pub fn child(&self) -> Option<NodeID> {
        debug_assert!(self.is_directory());
        let node = self.child as NodeID;
        if node.is_valid_node_id() {
            Some(node)
        } else {
            None
        }
    }

    /// Get the sibling of this node
    pub fn sibling(&self) -> Option<NodeID> {
        let node = self.sibling as NodeID;
        if node.is_valid_node_id() {
            Some(node)
        } else {
            None
        }
    }

    /// Get submodule node link (only for module nodes)
    pub fn linked_node(&self) -> NodeLink {
        debug_assert!(self.is_link());
        NodeLink {
            node: self.child,
            repository: self.address.context.into(),
            revision: self.address.hash,
        }
    }

    /// The node a link mounts in the revision it pins. `None` for anything else, whose `child`
    /// addresses the local tree instead and says nothing about a mount.
    pub fn mount_source(&self) -> Option<NodeID> {
        self.is_link().then_some(self.child)
    }

    /// Node ids are only comparable within one revision, so this answers for two nodes pinning
    /// the same one. Their shared [`address`](Self::address) cannot express the difference.
    pub fn mounts_same_source(&self, other: &Node) -> bool {
        self.mount_source() == other.mount_source()
    }

    /// Whether a link mounts the root of the revision it pins, which is the same node in every
    /// revision, so its mount needs no revision read to compare or carry.
    pub fn mounts_root(&self) -> bool {
        self.mount_source() == Some(ROOT_NODE)
    }

    /// A link's `child` names the subtree it mounts, so it has to travel with the address it is
    /// resolved against. Anything else keeps its `child`, which addresses the local tree.
    pub fn take_mount_source(&mut self, other: &Node) {
        if let Some(mount_source) = other.mount_source() {
            self.child = mount_source;
        }
    }

    /// Verify that this node, reached as a child of `expected_parent` during a
    /// tree walk, has its parent pointer matching. Detects cycles (a child
    /// pointer leading to an ancestor) and diamonds (a node referenced as a
    /// child by more than one parent). Should be invoked on every child the
    /// walk descends into and on every sibling along the chain.
    ///
    /// Returns a [`StateError`](crate::state::StateError) wrapping
    /// `InvalidNodeHierarchy` so callers can use `?` directly when they
    /// already work with `StateError`, or `.forward::<TargetError>(..)` to
    /// re-emit under another error set.
    pub fn check_parent_link(
        &self,
        node_id: NodeID,
        expected_parent: NodeID,
    ) -> Result<(), crate::state::StateError> {
        if self.parent != expected_parent {
            return Err(crate::state::StateError::from(InvalidNodeHierarchy {
                node: node_id,
                expected_parent,
                actual_parent: self.parent,
            }));
        }
        Ok(())
    }

    /// Combined per-step check for tree walks over a directory's sibling chain.
    /// Validates the parent back-pointer via [`Self::check_parent_link`] *and*
    /// records the visit with `cycle` to catch sibling cycles where every node
    /// has a legal parent pointer but the sibling links loop back on themselves
    /// (which the parent check alone cannot detect). Call once per node
    /// visited, including the first child.
    pub fn walk_step(
        &self,
        node_id: NodeID,
        expected_parent: NodeID,
        cycle: &mut SiblingCycleGuard,
    ) -> Result<(), crate::state::StateError> {
        self.check_parent_link(node_id, expected_parent)?;
        cycle
            .observe(node_id)
            .map_err(crate::state::StateError::from)?;
        Ok(())
    }
}

/// Allocation-free cycle detector for walking a directory's singly-linked
/// sibling chain (`Node::child` → `Node::sibling` → `Node::sibling` → …).
///
/// # Why it is needed
///
/// [`Node::check_parent_link`] catches cycles that reroute through a node
/// with a *different* parent pointer (the common shape of a tree-corruption
/// bug), but it cannot detect cycles where every node in the chain still
/// carries the correct parent ID — e.g. `P.child = A`, `A.sibling = B`,
/// `B.sibling = A`, all three with `parent = P`. The parent check is happy
/// and a naive walk loops forever.
///
/// # Algorithm
///
/// Brent's cycle-detection algorithm. We keep a single *snapshot* node and a
/// window length that doubles each time it expires:
///
/// * On every visit we compare the current node ID against the snapshot — if
///   they match, the chain has revisited a node, which is a cycle.
/// * Every `window` steps we advance the snapshot to the current node and
///   double `window`. So snapshots are taken at indices `2^k − 1` (1, 3, 7,
///   15, 31, …) and each remains active for `2^k` observations.
///
/// State is sixteen bytes (one `NodeID`, one `Option<NodeID>`, two `u32`s)
/// and stays on the stack — no heap allocation per iteration site.
///
/// # Proof that every cycle is caught
///
/// Let the chain be `x₀, x₁, …`. If it enters a cycle there exist unique
/// `μ ≥ 0` (tail length) and `λ ≥ 1` (cycle length) with `x_{μ+λ} = x_μ` and
/// `x_{i+λ} = x_i` for all `i ≥ μ`. Choose the smallest `k` with `2^k ≥ μ+λ`
/// and let `n = 2^k − 1`. Then:
///
/// 1. `n ≥ μ + λ − 1 ≥ μ`, so the snapshot `x_n` lies inside the cycle.
/// 2. The snapshot is active for the next `2^k = n + 1 ≥ λ + 1` observations
///    — i.e. throughout steps `n+1 .. 2n+1`.
/// 3. By cycle periodicity `x_{n+λ} = x_n`, and `n + λ ∈ [n+1, 2n+1]` because
///    `λ ≤ 2^k`. So observation `n + λ` matches the active snapshot and the
///    guard returns an error.
///
/// Equality of `NodeID`s implies identity, so the check has no false
/// positives.
///
/// # Worst-case iteration count
///
/// Detection occurs at step `n + λ ≤ 3(μ + λ) − 2`, i.e. *O(μ + λ)* —
/// linear in the chain length, with a worst-case constant of `~3×`
/// (hit when `μ + λ` is just above a power of two). On a clean chain of
/// length `N` the guard adds one `NodeID` compare and one `u32` increment
/// per step and never returns an error. For `N = 2^16` the worst case is
/// under `196 608` observations.
#[derive(Debug, Clone, Copy)]
pub struct SiblingCycleGuard {
    /// Parent whose child/sibling chain is being walked.
    parent_node_id: NodeID,
    /// Most recent snapshot — every observation is compared against this.
    snapshot: Option<NodeID>,
    /// Observations since the last snapshot was taken.
    steps: u32,
    /// Snapshot window length; doubles each time it expires.
    window: u32,
}

impl SiblingCycleGuard {
    pub const fn new(parent_node_id: NodeID) -> Self {
        Self {
            parent_node_id,
            snapshot: None,
            steps: 0,
            window: 1,
        }
    }

    /// Record an observation of `node_id` as the next visited node in the
    /// chain. Returns `InvalidNodeHierarchy` if `node_id` matches the active
    /// snapshot, signalling a sibling-chain cycle.
    pub fn observe(&mut self, node_id: NodeID) -> Result<(), InvalidNodeHierarchy> {
        if self.snapshot == Some(node_id) {
            return Err(InvalidNodeHierarchy {
                node: node_id,
                expected_parent: self.parent_node_id,
                actual_parent: node_id,
            });
        }
        if self.steps == self.window {
            self.snapshot = Some(node_id);
            self.steps = 0;
            self.window = self.window.saturating_mul(2);
        }
        self.steps += 1;
        Ok(())
    }
}

