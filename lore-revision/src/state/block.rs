/// Under `state-hooks`, a writer's record of the nodes it handed out mutably, for the log's `Word`
/// records: each node's record at its first hand-out, and the block's pending clear bits at the
/// lock, compared as the writer releases. The snapshots go into a buffer per thread, reused, which
/// several live writers share.
#[cfg(feature = "state-hooks")]
mod words {
    use std::cell::Cell;
    use std::cell::RefCell;
    use std::sync::atomic::AtomicU64;
    use std::sync::atomic::Ordering;

    use super::BLOCK_NODE_COUNT;
    use super::BLOCK_NODE_SHIFT;
    use super::Node;
    use super::NodeBlock;
    use super::NodeBlockRuntimeData;
    use crate::state::node::hooks::log;

    /// The words of a block's bitmaps, one bit per node.
    const WORDS: usize = BLOCK_NODE_COUNT / 64;

    /// A node's record at its first hand-out by writer `writer`.
    struct Snapshot {
        writer: u32,
        index: u16,
        record: Node,
    }

    thread_local! {
        static SNAPSHOTS: RefCell<Vec<Snapshot>> = const { RefCell::new(Vec::new()) };
        static NEXT_WRITER: Cell<u32> = const { Cell::new(0) };
    }

    /// Snapshots pushed into a full buffer, every thread's: each an allocation under a lock.
    static GROWN: AtomicU64 = AtomicU64::new(0);

    /// How many snapshots were pushed into a full buffer.
    pub(crate) fn grown() -> u64 {
        GROWN.load(Ordering::Relaxed)
    }

    /// Pushes `snapshot`, counting a push that grows the buffer.
    fn push(snapshots: &mut Vec<Snapshot>, snapshot: Snapshot) {
        if snapshots.len() == snapshots.capacity() {
            GROWN.fetch_add(1, Ordering::Relaxed);
        }
        snapshots.push(snapshot);
    }

    /// The first hand-out's snapshot, out of line, so a hand-out inlined at every `node()` keeps
    /// only its bitmap test.
    #[inline(never)]
    fn snapshot(writer: u32, index: usize, record: &Node) {
        SNAPSHOTS.with_borrow_mut(|snapshots| {
            push(
                snapshots,
                Snapshot {
                    writer,
                    index: index as u16,
                    record: *record,
                },
            );
        });
    }

    /// Tops the thread's snapshot buffer up to room for two whole blocks, outside every section,
    /// so a writer's snapshots allocate nothing under its lock.
    pub(crate) fn reserve() {
        SNAPSHOTS.with_borrow_mut(|snapshots| {
            if snapshots.capacity() - snapshots.len() < 2 * BLOCK_NODE_COUNT {
                snapshots.reserve(4 * BLOCK_NODE_COUNT);
            }
        });
    }

    #[inline]
    fn bit(words: &[u64; WORDS], index: usize) -> bool {
        words[index / 64] & (1 << (index % 64)) != 0
    }

    #[inline]
    fn set(words: &mut [u64; WORDS], index: usize, on: bool) {
        if on {
            words[index / 64] |= 1 << (index % 64);
        } else {
            words[index / 64] &= !(1 << (index % 64));
        }
    }

    /// Whether a node's words differ as the log tells them: its flag word, its extension word, its
    /// content, and a link's `child`. Its place in its chain and its name are structure, which the
    /// structural records tell.
    fn words_differ(was: &Node, is: &Node) -> bool {
        was.flags != is.flags
            || was.ext_flags != is.ext_flags
            || was.address != is.address
            || was.size != is.size
            || was.mode != is.mode
            || ((was.is_link() || is.is_link()) && was.child != is.child)
    }

    /// A writer's part of the buffer.
    pub(super) struct Words {
        /// The writer's number on its thread, `None` where the thread did not record at the lock
        /// or the block is not installed.
        id: Option<u32>,
        /// The block's pending clear bits at the lock.
        clear_pending: [u64; WORDS],
        /// The nodes the writer snapshotted.
        handed: [u64; WORDS],
        /// The nodes the writer freed, and did not grab again since.
        freed: [u64; WORDS],
    }

    impl Words {
        /// A writer's record, recording where the thread does (`recording`) and `block` is
        /// installed.
        pub(super) fn begin(block: &NodeBlock, recording: bool) -> Self {
            let mut clear_pending = [0; WORDS];
            let id = (recording && block.hooks.name().is_some()).then(|| {
                for (word, bits) in clear_pending.iter_mut().zip(&block.clear_pending) {
                    *word = bits.load(Ordering::Relaxed);
                }
                NEXT_WRITER.with(|next| {
                    let id = next.get();
                    next.set(id.wrapping_add(1));
                    id
                })
            });
            Self {
                id,
                clear_pending,
                handed: [0; WORDS],
                freed: [0; WORDS],
            }
        }

        /// The node at `index`, `record`, handed out mutably.
        #[inline]
        pub(super) fn handed(&mut self, index: usize, record: &Node) {
            let Some(id) = self.id else {
                return;
            };
            if bit(&self.handed, index) {
                return;
            }
            set(&mut self.handed, index, true);
            snapshot(id, index, record);
        }

        /// Every node of the block handed out mutably: those not handed out before, in one pass.
        pub(super) fn handed_all(&mut self, nodes: &[Node]) {
            let Some(id) = self.id else {
                return;
            };
            if self.handed == [u64::MAX; WORDS] {
                return;
            }
            SNAPSHOTS.with_borrow_mut(|snapshots| {
                for (index, record) in nodes.iter().enumerate() {
                    if !bit(&self.handed, index) {
                        push(
                            snapshots,
                            Snapshot {
                                writer: id,
                                index: index as u16,
                                record: *record,
                            },
                        );
                    }
                }
            });
            self.handed = [u64::MAX; WORDS];
        }

        /// The node at `index` freed by the writer: a free's own change is the model's.
        pub(super) fn freed(&mut self, index: usize) {
            if self.id.is_some() {
                set(&mut self.freed, index, true);
            }
        }

        /// The node at `index` grabbed by the writer: from here its words are compared with
        /// `grabbed`, the record a grab leaves as the model applies it, not with what the slot
        /// held before.
        pub(super) fn grabbed(&mut self, index: usize, grabbed: &Node) {
            let Some(id) = self.id else {
                return;
            };
            set(&mut self.freed, index, false);
            if !bit(&self.handed, index) {
                self.handed(index, grabbed);
                return;
            }
            SNAPSHOTS.with_borrow_mut(|snapshots| {
                if let Some(snapshot) = snapshots
                    .iter_mut()
                    .rev()
                    .find(|snapshot| snapshot.writer == id && snapshot.index as usize == index)
                {
                    snapshot.record = *grabbed;
                }
            });
        }

        /// The writer releasing: a `Word` for each node it handed out whose words or pending
        /// clear bit changed and that is not free, and for each node whose bit alone changed, in
        /// index order, with nothing allocated.
        pub(super) fn end(&mut self, block: &NodeBlock, runtime: &NodeBlockRuntimeData) {
            let Some(id) = self.id.take() else {
                return;
            };
            let (Some(state), Some((_, block_index))) =
                (block.hooks.state.get(), block.hooks.name())
            else {
                return;
            };
            let node_count = runtime.data.node_count as usize;
            let mut now = [0u64; WORDS];
            for (word, bits) in now.iter_mut().zip(&block.clear_pending) {
                *word = bits.load(Ordering::Relaxed);
            }
            let node_id = |index: usize| ((block_index as u32) << BLOCK_NODE_SHIFT) | index as u32;
            let mut changed = [0u64; WORDS];
            let _ = SNAPSHOTS.try_with(|snapshots| {
                // A release on a path that holds the buffer, which none does, records nothing,
                // counted for the driver to fail the run on.
                let Ok(mut snapshots) = snapshots.try_borrow_mut() else {
                    log::fault();
                    return;
                };
                snapshots.retain(|snapshot| {
                    if snapshot.writer != id {
                        return true;
                    }
                    let index = snapshot.index as usize;
                    let moved = words_differ(&snapshot.record, &runtime.data.node[index])
                        || bit(&now, index) != bit(&self.clear_pending, index);
                    if moved && !bit(&self.freed, index) && index < node_count {
                        set(&mut changed, index, true);
                    }
                    false
                });
            });
            for (word, ((was, is), handed)) in changed
                .iter_mut()
                .zip(self.clear_pending.iter().zip(&now).zip(&self.handed))
            {
                *word |= (was ^ is) & !handed;
            }
            for (at, word) in changed.into_iter().enumerate() {
                let mut bits = word;
                while bits != 0 {
                    let index = at * 64 + bits.trailing_zeros() as usize;
                    bits &= bits - 1;
                    log::record(
                        state,
                        log::Effect::Word {
                            node: node_id(index),
                            record: log::Words(runtime.data.node[index]),
                            clear_pending: bit(&now, index),
                        },
                    );
                }
            }
        }
    }
}

/// Under `state-hooks`, the node blocks this thread holds a guard of, by install index, so a
/// guard taken out of order panics before it can deadlock: blocks lock in ascending index, each
/// once (C13). An owned reader, which may be released on another thread, is not tracked.
#[cfg(feature = "state-hooks")]
mod lock_order {
    use std::cell::RefCell;

    /// The most block guards one thread holds at once: `BlockLocks` takes six.
    const MOST: usize = 16;

    /// The guards held, in an inline array, so tracking allocates nothing inside a counted
    /// request.
    struct HeldGuards {
        guards: [(usize, usize); MOST],
        len: usize,
    }

    thread_local! {
        static HELD: RefCell<HeldGuards> = const {
            RefCell::new(HeldGuards {
                guards: [(0, 0); MOST],
                len: 0,
            })
        };
    }

    /// A node block guard this thread holds, by its State and install index; dropped with it.
    pub(super) struct Held(usize, usize);

    /// The node block guards this thread holds.
    pub(super) fn held() -> usize {
        HELD.with_borrow(|held| held.len)
    }

    /// Records that this thread takes a guard of the block State `owner` installed at `index`,
    /// asserting it holds none of that State's at that index or above. Blocks not installed
    /// yet, which no other task reaches, are not tracked.
    pub(super) fn taking(owner: usize, index: usize) -> Option<Held> {
        if index == usize::MAX {
            return None;
        }
        HELD.with_borrow_mut(|held| {
            if let Some((_, above)) = held.guards[..held.len]
                .iter()
                .find(|&&(of, at)| of == owner && at >= index)
            {
                panic!(
                    "node block {index} locked while this thread holds block {above}: blocks \
                     lock in ascending index, each once"
                );
            }
            assert!(held.len < MOST, "more than {MOST} node block guards held");
            held.guards[held.len] = (owner, index);
            held.len += 1;
        });
        Some(Held(owner, index))
    }

    impl Drop for Held {
        fn drop(&mut self) {
            let _ = HELD.try_with(|held| {
                if let Ok(mut held) = held.try_borrow_mut()
                    && let Some(at) = held.guards[..held.len]
                        .iter()
                        .rposition(|&entry| entry == (self.0, self.1))
                {
                    held.len -= 1;
                    let last = held.guards[held.len];
                    held.guards[at] = last;
                }
            });
        }
    }
}

/// Under `state-hooks`, the node block guards this thread holds, which a task may not hold at a
/// scheduling point (C13). Owned guards are not among them.
#[cfg(feature = "state-hooks")]
pub(crate) fn block_guards_held() -> usize {
    lock_order::held()
}

